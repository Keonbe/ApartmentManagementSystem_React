// Writes src/assets/styles/themes.generated.css, the colour remap behind the
// user side's Dark and Glass themes: `node scripts/gen-theme-css.mjs`.
//
// Tailwind 4 resolves bg-* through --background-color-*, text-* through
// --text-color-*, border-* through --border-color-* (and so on) before falling
// back to --color-*. The @theme block below defines those per-property names
// for the colours the light pages use, pointing at the normal palette; the
// .ut-dark / .ut-glass blocks redefine them. So `bg-white` turns into a dark
// surface while `text-white` on a button stays white, and every variant
// (hover:, disabled:, bg-white/80 …) follows without extra rules.
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

