    border: { brand: 'rgb(199 210 254 / 0.4)', white: 'rgb(255 255 255 / 0.14)', 'slate-50': 'rgb(255 255 255 / 0.06)', 'slate-100': 'rgb(255 255 255 / 0.08)', 'slate-200': 'rgb(255 255 255 / 0.12)', 'slate-300': 'rgb(255 255 255 / 0.2)', 'slate-400': 'rgb(255 255 255 / 0.28)' },
