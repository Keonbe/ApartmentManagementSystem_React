    text: { brand: '#a5b4fc', 'slate-950': '#f1f5f9', 'slate-900': '#f1f5f9', 'slate-800': '#e2e8f0', 'slate-700': '#cbd5e1', 'slate-600': '#a9b6c8', 'slate-500': '#8d9bb0', 'slate-400': '#6f7e94', 'slate-300': '#4b5a70', 'slate-200': '#334155' },
